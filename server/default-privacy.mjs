/** Upgrade only the exact known default. Unknown custom text remains intact and
 * must be reviewed by the operator; the page renders current rules separately. */
export function effectivePrivacyDocument(saved) {
  const source = saved && typeof saved === "object" && !Array.isArray(saved) ? saved : {};
  const content = typeof source.content === "string" ? source.content : "";
  const trimmed = content.trim();
  const upgradedLegacyDefault = trimmed === LEGACY_DEFAULT_PRIVACY_CONTENT.content.trim();
  const currentDefault = !trimmed || trimmed === DEFAULT_PRIVACY_CONTENT.content.trim();
  return {
    document: {
      title: typeof source.title === "string" && source.title.trim() ? source.title : DEFAULT_PRIVACY_CONTENT.title,
      content: upgradedLegacyDefault || currentDefault ? DEFAULT_PRIVACY_CONTENT.content : content,
    },
    upgradedLegacyDefault,
    customNeedsReview: !upgradedLegacyDefault && !currentDefault,
  };
}
